"""Tiny i18n helper for the safe-url-guard command-line tools (English / 简体中文).

Language is chosen in this order:
  1. the SAFE_URL_GUARD_LANG environment variable ("en" or "zh")
  2. the `.lang` file next to this script (written by `python3 safe_url_guard.py lang zh`)
  3. the system locale (LANG / LC_ALL / LC_MESSAGES starting with "zh" -> Chinese)
  4. English
"""

from __future__ import annotations

import os
from pathlib import Path

LANG_FILE = Path(__file__).resolve().parent / ".lang"
SUPPORTED = ("en", "zh")


def detect() -> str:
    env = os.environ.get("SAFE_URL_GUARD_LANG", "").strip().lower()
    if env[:2] in SUPPORTED:
        return env[:2]
    try:
        saved = LANG_FILE.read_text(encoding="utf-8").strip().lower()
        if saved[:2] in SUPPORTED:
            return saved[:2]
    except OSError:
        pass
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        if os.environ.get(var, "").lower().startswith("zh"):
            return "zh"
    return "en"


LANG = detect()


def set_lang(lang: str) -> None:
    global LANG
    LANG = lang
    LANG_FILE.write_text(lang + "\n", encoding="utf-8")


def pick(value):
    """Return the right language from {"en": ..., "zh": ...}; plain values pass through."""
    if isinstance(value, dict) and "en" in value:
        return value.get(LANG, value["en"])
    return value


def t(key: str, **kw) -> str:
    msg = MESSAGES[key]
    return pick(msg).format(**kw)


